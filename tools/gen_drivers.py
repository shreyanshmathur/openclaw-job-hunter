_PY_ONLY = re.compile(r"\(\?P|\(\?[aiLmsux]+[):]|\(\?<[=!]|\\A|\\Z|\(\?#")
_ID_RE = re.compile(r"^[a-z0-9_]{1,60}$")


def severity() -> tuple:
    """jobhunter.detect.SEVERITY (U1), so the page ranks reasons exactly as `jh.py detect` does."""
    scripts = os.path.join(REPO, "scripts")
    if scripts not in sys.path:
        sys.path.insert(0, scripts)
    try:
        from jobhunter import detect
        return tuple(detect.SEVERITY)
    except Exception:   # the generator still works when U1's module is broken or absent
        return SEVERITY_FALLBACK


def _valid(p) -> bool:
    if not isinstance(p, str) or not p or len(p) > 300:
        return False
    try:
        p.encode("ascii")
        re.compile(p)
    except (UnicodeEncodeError, re.error):
        return False
    return not _PY_ONLY.search(p)


def _sig(sid: str, reason: str, where: str, pattern: str) -> dict:
    """One embedded signature; a JOB_LEVEL reason is a job-level stop (trip false, job_needs_human)."""
    if reason in JOB_LEVEL:
        return {"id": sid, "reason_code": None, "trip": False, "job_needs_human": reason, where: pattern}
    return {"id": sid, "reason_code": reason, "trip": True, "job_needs_human": None, where: pattern}


def _from_file(data: dict, fam: str) -> list:
    """Stop signatures of one detect/*.json file with a url, title or text regex, in file order."""
    out = []
    for i, s in enumerate(data.get("signatures") or []):
        if not isinstance(s, dict) or s.get("verdict", "stop") != "stop":
            continue
        sid = s["id"] if isinstance(s.get("id"), str) and _ID_RE.match(s["id"]) else "%s_file_%d" % (fam, i + 1)
        rc = s.get("reason_code") if isinstance(s.get("reason_code"), str) else None
        jnh = s.get("job_needs_human") if isinstance(s.get("job_needs_human"), str) else None
        for where in WHERE:
            if _valid(s.get(where)):
                out.append({"id": sid, "reason_code": rc, "trip": bool(s.get("trip")), "job_needs_human": jnh,
                            where: s[where]})
    return out


def signatures(detect_dir: str = DETECT_DIR) -> dict:
    """{family: [signature, ...]}: detect file signatures, then the baseline, then the common patterns (a
    (where, pattern) pair already embedded for the family is not repeated), then the probes."""
    sig = {}
    for fam in FAMILIES:
        items = []
        try:
            with open(os.path.join(detect_dir, fam + ".json"), "r", encoding="utf-8") as fh:
                items += _from_file(json.load(fh), fam)
        except (OSError, ValueError, AttributeError):
            pass
        for n, (where, pat, reason) in enumerate(BASELINE[fam], 1):
            items.append(_sig("baseline_%s_%d" % (fam, n), reason, where, pat))
        for n, (where, pat, kind) in enumerate(COMMON, 1):
            items.append(_sig("common_%s_%d" % (fam, n), COMMON_REASON[fam][kind], where, pat))
        seen, uniq = set(), []
        for s in items:
            where = next(w for w in WHERE if w in s)
            if not _valid(s[where]) or (where, s[where]) in seen:
                continue
            seen.add((where, s[where]))
            uniq.append(s)
        uniq += [_sig("probe_" + probe, reason, "probe", probe) for probe, reason in PROBES[fam]]
        sig[fam] = uniq
    return sig


def rank(sig: dict, order: int, sev=None) -> tuple:
    """Sort key of a matching signature (smaller wins), the same as jobhunter.detect._rank and the page."""
    sev = list(sev if sev is not None else severity())
    rc = sig.get("reason_code") or ""
    return (0 if sig.get("trip") else 1, sev.index(rc) if rc in sev else len(sev), order)


def render_block(sig: dict, sev=None) -> str:
    sev = list(sev if sev is not None else severity())
    lines = [BEGIN, "  const SEVERITY = %s;" % json.dumps(sev, ensure_ascii=True), "  const SIG = {"]
    fams = [f for f in FAMILIES if f in sig]
    for i, fam in enumerate(fams):
        body = json.dumps(sig[fam], ensure_ascii=True, sort_keys=True)
        lines.append("    %s: %s%s" % (fam, body, "," if i < len(fams) - 1 else ""))
    lines += ["  };", END]
    return "\n".join(lines)


def parse_block(text: str) -> tuple:
    """(SEVERITY, SIG) read back from a detect_page.js text (tests)."""
    block = text[text.index(BEGIN):text.index(END)]
    m = re.search(r"const SEVERITY = (\[.*?\]);", block)
    sev = json.loads(m.group(1)) if m else []
    sig = {fam: json.loads(body) for fam, body in re.findall(r"^ {4}(\w+): (\[.*\]),?$", block, flags=re.M)}
    return sev, sig


def embed(text: str, sig: dict, sev=None) -> str:
    start = text.index(BEGIN)
    stop = text.index(END, start) + len(END)
    return text[:start] + render_block(sig, sev) + text[stop:]


def function_text(content: str) -> str:
    return content.strip()


def sha256_function(content: str) -> str:
    return hashlib.sha256(function_text(content).encode("utf-8")).hexdigest()


def build(drivers_dir: str = DRIVERS_DIR, detect_dir: str = DETECT_DIR) -> dict:
    """{path: new content} for detect_page.js and manifest.json."""
    out = {}
    det = os.path.join(drivers_dir, DETECT_DRIVER)
    with open(det, "r", encoding="utf-8") as fh:
        out[det] = function_text(embed(fh.read(), signatures(detect_dir))) + "\n"
    manifest = {}
    for path in sorted(glob.glob(os.path.join(drivers_dir, "*.js"))):
        if path in out:
            content = out[path]
        else:
            with open(path, "r", encoding="utf-8") as fh:
                content = fh.read()
        manifest[os.path.splitext(os.path.basename(path))[0]] = sha256_function(content)
    out[os.path.join(drivers_dir, "manifest.json")] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when a generated file is out of date")
    args = ap.parse_args(argv)
    stale = []
    for path, content in build().items():
        try:
            with open(path, "r", encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != content:
            stale.append(os.path.relpath(path, REPO))
            if not args.check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(content)
    if args.check and stale:
        print("out of date: %s (run python3 tools/gen_drivers.py)" % ", ".join(stale))
        return 1
    print("updated: %s" % (", ".join(stale) if stale else "nothing"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
