DETECT_DRIVER = "detect_page.js"
BEGIN = "  /* BEGIN SIGNATURES (generated by tools/gen_drivers.py; do not edit by hand) */"
END = "  /* END SIGNATURES */"
FAMILIES = ("linkedin", "gmail", "ats", "boards")
WHERE = ("url", "title", "text")

