#!/usr/bin/env python3
"""Generate the driver artefacts (design 10.1, 1.4 R4): embed the stop signatures into
drivers/detect_page.js and write drivers/manifest.json = {driver name: sha256 of its exact function text}.

    python3 tools/gen_drivers.py            # regenerate in place
    python3 tools/gen_drivers.py --check    # exit 1 when a file is out of date (CI)

Signatures: every stop signature of scripts/jobhunter/detect/{linkedin,gmail,ats,boards}.json (U1) that has a
url, title or text regex, in file order, followed by the research baseline below (linkedin-limits.md section
4, design 4.5), the patterns common to every family and the structural probes. Each embedded signature keeps
its id, reason_code, trip and job_needs_human, so the page picks the most severe hit the way `jh.py detect`
does (jobhunter.detect._rank): a tripping stop before a job-level stop, then the reason's place in
jobhunter.detect.SEVERITY (embedded too, so there is one source), then the order above. HTTP-status
signatures are not embedded (a page script cannot see the status); `jh.py detect` and the guard still match
them. Only patterns that compile in Python and use no Python-only syntax are embedded, so the page can run
them with `new RegExp(p, 'i')`.

Function text and hash: the driver file content with surrounding whitespace removed (str.strip()), UTF-8;
the agent passes exactly that text to the browser `evaluate` action and the guard compares its sha256 with
the manifest after the same strip.
"""
